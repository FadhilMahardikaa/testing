"""Koneksi PostgreSQL (Neon/Vercel) dan pembuatan skema database.

Semua nilai uang disimpan sebagai bilangan rupiah bulat, bukan float.
"""
import os
from contextlib import contextmanager

import psycopg
from psycopg.rows import dict_row


def connect():
    url = os.environ.get('DATABASE_URL')
    if not url:
        raise RuntimeError('DATABASE_URL belum diatur. Buat PostgreSQL di Neon dan hubungkan ke Vercel.')
    # Neon pooler menggunakan PgBouncer transaction pooling. Hindari prepared statements.
    return psycopg.connect(url, row_factory=dict_row, connect_timeout=10, prepare_threshold=None)


@contextmanager
def db_session():
    with connect() as conn:
        try:
            yield conn
            conn.commit()
        except Exception:
            conn.rollback()
            raise


def init_db():
    """Idempotent: aman dieksekusi saat instance serverless mulai."""
    with db_session() as db:
        db.execute('''CREATE TABLE IF NOT EXISTS suppliers (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            phone TEXT NOT NULL DEFAULT '',
            address TEXT NOT NULL DEFAULT '',
            active BOOLEAN NOT NULL DEFAULT TRUE
        )''')
        db.execute('CREATE UNIQUE INDEX IF NOT EXISTS idx_suppliers_name_ci ON suppliers(LOWER(name))')
        db.execute('''CREATE TABLE IF NOT EXISTS products (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            sku TEXT NOT NULL,
            name TEXT NOT NULL,
            category TEXT NOT NULL DEFAULT 'Lainnya',
            cost BIGINT NOT NULL CHECK(cost >= 0),
            price BIGINT NOT NULL CHECK(price >= 0),
            stock BIGINT NOT NULL DEFAULT 0 CHECK(stock >= 0),
            min_stock BIGINT NOT NULL DEFAULT 5 CHECK(min_stock >= 0),
            expiry_date DATE,
            supplier_id BIGINT REFERENCES suppliers(id) ON DELETE SET NULL,
            active BOOLEAN NOT NULL DEFAULT TRUE,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )''')
        db.execute('CREATE UNIQUE INDEX IF NOT EXISTS idx_products_sku_ci ON products(LOWER(sku))')
        db.execute('''CREATE TABLE IF NOT EXISTS movements (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            product_id BIGINT NOT NULL REFERENCES products(id),
            type TEXT NOT NULL CHECK(type IN ('IN','OUT','ADJUST')),
            qty_change BIGINT NOT NULL CHECK(qty_change != 0),
            stock_after BIGINT NOT NULL CHECK(stock_after >= 0),
            reason TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )''')
        db.execute('CREATE INDEX IF NOT EXISTS idx_movements_product ON movements(product_id)')
        db.execute('CREATE INDEX IF NOT EXISTS idx_movements_created ON movements(created_at)')
